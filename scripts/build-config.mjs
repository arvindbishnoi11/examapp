// =============================================================================
// PrepSetu — build-time public configuration
// =============================================================================
// Generates `public/env.js` (window.__PREPSETU_ENV__) and
// `public/firebase-messaging-sw.js` from environment variables.
//
// ONLY public values belong here (Firebase web config, spreadsheet id, super
// admin email, VAPID public key). The script refuses to emit anything that
// looks like a private key so a mis-pasted secret cannot reach a browser
// bundle.
// =============================================================================

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

/** Minimal .env parser (KEY=VALUE, # comments, optional quotes). */
function parseEnvFile(path) {
  const vars = {};
  if (!existsSync(path)) return vars;
  const text = readFileSync(path, 'utf8');
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    vars[key] = value;
  }
  return vars;
}

