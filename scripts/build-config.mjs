const out = {};
for (const [key, fallback] of Object.entries(DEFAULTS)) {
  const value = env[key] ?? fallback;
  out[key.replace(/^VITE_/, '')] = value;
}

// ---- Safety net: never ship secrets ---------------------------------------
const FORBIDDEN_PATTERNS = [
  /BEGIN (RSA |EC )?PRIVATE KEY/,
  /-----BEGIN/,
  /"private_key"\s*:/,
  /AIza[0-9A-Za-z_-]{35}[\s\S]*private_key/i,
];
const FORBIDDEN_KEYS = /^(GOOGLE_SERVICE_ACCOUNT_JSON|FIREBASE_SERVICE_ACCOUNT_JSON|YOUTUBE_API_KEY|ADMIN_SESSION_SECRET|IP_HASH_SECRET|SUPER_ADMIN_EMAIL)$/;
const violations = [];
for (const [key, value] of Object.entries(out)) {
  if (!key.startsWith('FIREBASE_') && !key.startsWith('SUPER_ADMIN') && !key.startsWith('GOOGLE_') && !key.startsWith('RECAPTCHA') && !key.startsWith('AUTH_') && !key.startsWith('APP_') && !key.startsWith('USE_')) continue;
  if (FORBIDDEN_KEYS.test(key) && !key.startsWith('SUPER_ADMIN_')) violations.push(key);
  for (const pattern of FORBIDDEN_PATTERNS) {
    if (pattern.test(String(value))) violations.push(`${key} (value matches a secret pattern)`);
  }
}
if (violations.length) {
  console.error('\n✖ Refusing to build: secret material detected in public config:');
  for (const v of violations) console.error(`   - ${v}`);
  console.error('  Public configuration must never contain private keys or server secrets.\n');
  process.exit(1);
}

